const withOxlint = (name: string, body: () => void): void => {
  if (HAS_OXLINT) {
    describe(name, body);
    return;
  }
  if (IN_CI) {
    describe(name, () => {
      it('needs oxlint and the built plugin, which CI must provide', () => {
        expect({
          oxlint: existsSync(OXLINT_BIN),
          plugin: existsSync(PLUGIN),
        }).toEqual({ oxlint: true, plugin: true });
      });
    });
    return;
  }
  describe.skip(name, body);
};

let sequence = 0;

const pair = (
  tool: string,
  input: ToolInput,
  extra: Partial<HookPayload> = {},
): { pre: HookPayload; post: HookPayload } => {
  sequence += 1;
  const id = `toolu_${process.pid}_${sequence}`;
  const base = { tool_name: tool, tool_use_id: id, tool_input: input };
  return {
    pre: { ...extra, ...base, hook_event_name: 'PreToolUse' },
    post: { ...extra, ...base, hook_event_name: 'PostToolUse' },
  };
};

const configFor = (
  config: LegionConfig,
  overrides: Record<string, unknown> = {},
): string =>
  `${JSON.stringify({ ...config.oxlint, jsPlugins: [PLUGIN], ...overrides }, null, 2)}\n`;

const projects: string[] = [];

const put = (dir: string, path: string, content: string): string => {
  const full = join(dir, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
  return full;
};

const project = (files: Record<string, string>, base = ROOT): string => {
  const dir = realpathSync(mkdtempSync(join(base, 'steer-it-')));
  projects.push(dir);
  for (const [path, content] of Object.entries(files)) put(dir, path, content);
  return dir;
};

const outsideAnyInstall = (files: Record<string, string>): string =>
  project(files, realpathSync(tmpdir()));

afterAll(() => {
  for (const dir of projects) rmSync(dir, { recursive: true, force: true });
});

const git = (cwd: string, ...args: string[]): string => {
  const result = spawnSync(
    'git',
    [
      '-c',
      'user.name=legion-steer',
      '-c',
      'user.email=steer@example.invalid',
      '-c',
      'commit.gpgsign=false',
      ...args,
    ],
    { cwd, encoding: 'utf8' },
  );
  if (result.status !== 0) {
    throw new Error(`git ${args.join(' ')} failed: ${result.stderr}`);
  }
  return result.stdout;
};

const commitAll = (dir: string): void => {
  git(dir, 'init', '-q');
  git(dir, 'add', '-A');
  git(dir, 'commit', '-q', '-m', 'baseline');
};

const throughBash = (dir: string, command: string): HookVerdict => {
  const { pre, post } = pair('Bash', { command });
  expect(evaluate(dir, pre)).toMatchObject({ action: 'allow', notices: [] });
  const ran = spawnSync('bash', ['-c', command], {
    cwd: dir,
    encoding: 'utf8',
  });
  expect({ status: ran.status, stderr: ran.stderr }).toMatchObject({
    status: 0,
  });
  return evaluate(dir, post);
};

const rulesOf = (verdict: HookVerdict): string[] =>
  verdict.findings.map((finding) => finding.rule);

const recommendedProject = (files: Record<string, string> = {}): string =>
  project({ '.oxlintrc.json': configFor(recommended), ...files });

withOxlint('Write', () => {
  it('blocks a violating write before it lands', () => {
    const dir = recommendedProject({ 'src/.keep': '' });
    const target = join(dir, 'src', 'Color.ts');
    const verdict = evaluate(
      dir,
      pair('Write', { file_path: target, content: ENUM }).pre,
    );
    expect(verdict.action).toBe('block');
    expect(rulesOf(verdict)).toContain('legion/no-enum');
    expect(verdict.findings[0]?.file).toBe(join('src', 'Color.ts'));
    expect(existsSync(target)).toBe(false);
  });

  it('lets a clean write through without a word', () => {
    const dir = recommendedProject();
    const { pre, post } = pair('Write', {
      file_path: join(dir, 'answer.ts'),
      content: CLEAN,
    });
    expect(evaluate(dir, pre)).toMatchObject({
      action: 'allow',
      linted: true,
      notices: [],
    });
    expect(evaluate(dir, post)).toMatchObject({ action: 'allow', notices: [] });
  });

  it('blocks a write into a directory that does not exist yet, and leaves no trace', () => {
    const dir = recommendedProject();
    const target = join(dir, 'src', 'deep', 'new', 'Color.ts');
    const verdict = evaluate(
      dir,
      pair('Write', { file_path: target, content: ENUM }).pre,
    );
    expect(verdict.action).toBe('block');
    expect(existsSync(join(dir, 'src'))).toBe(false);
  });

  it('treats a write from a subagent exactly like one from the main agent', () => {
    const dir = recommendedProject();
    const verdict = evaluate(
      dir,
      pair(
        'Write',
        { file_path: join(dir, 'Color.ts'), content: ENUM },
        { agent_id: 'agent-7', agent_type: 'general-purpose', session_id: 's' },
      ).pre,
    );
    expect(verdict.action).toBe('block');
  });
});

withOxlint('Edit and MultiEdit, checked before they land', () => {
  it('blocks an edit that would introduce a violation', () => {
    const dir = recommendedProject({ 'src/answer.ts': CLEAN });
    const target = join(dir, 'src', 'answer.ts');
    const verdict = evaluate(
      dir,
      pair('Edit', {
        file_path: target,
        old_string: 'export const answer = 42;',
        new_string: 'export enum Answer {\n  Yes,\n}',
      }).pre,
    );
    expect(verdict.action).toBe('block');
    expect(rulesOf(verdict)).toEqual(['legion/no-enum']);
    expect(readFileSync(target, 'utf8')).toBe(CLEAN);
  });

  it('lets an edit through when the file already had the violation, and says so', () => {
    const dir = recommendedProject({ 'src/legacy.ts': `${ENUM}${CLEAN}` });
    const verdict = evaluate(
      dir,
      pair('Edit', {
        file_path: join(dir, 'src', 'legacy.ts'),
        old_string: '42',
        new_string: '43',
      }).pre,
    );
    expect(verdict.action).toBe('allow');
    expect(verdict.notices.join('\n')).toContain('already in this file');
  });

  it('blocks a MultiEdit when any edit in the batch introduces a violation', () => {
    const dir = recommendedProject({ 'src/answer.ts': CLEAN });
    const verdict = evaluate(
      dir,
      pair('MultiEdit', {
        file_path: join(dir, 'src', 'answer.ts'),
        edits: [
          { old_string: '42', new_string: '43' },
          {
            old_string: 'export const answer = 43;',
            new_string: 'export enum Answer {\n  Yes,\n}',
          },
        ],
      }).pre,
    );
    expect(verdict.action).toBe('block');
    expect(rulesOf(verdict)).toEqual(['legion/no-enum']);
  });

  it('falls back to checking right after an edit it cannot replay, and says so', () => {
    const dir = recommendedProject({ 'src/answer.ts': CLEAN });
    const target = join(dir, 'src', 'answer.ts');
    const { pre, post } = pair('Edit', {
      file_path: target,
      old_string: 'export const answer = 42 ;',
      new_string: 'export enum Answer {\n  Yes,\n}',
    });
    const before = evaluate(dir, pre);
    expect(before.action).toBe('allow');
    expect(before.notices[0]).toContain('lints the file right after');
    writeFileSync(target, 'export enum Answer {\n  Yes,\n}\n');
    const after = evaluate(dir, post);
    expect(after.action).toBe('report');
    expect(rulesOf(after)).toEqual(['legion/no-enum']);
  });

  it('still reports after the fact when no pre-check ran, as older settings had it', () => {
    const dir = recommendedProject({ 'src/Color.ts': ENUM });
    const verdict = evaluate(
      dir,
      pair('Edit', { file_path: join(dir, 'src', 'Color.ts') }).post,
    );
    expect(verdict.action).toBe('report');
  });
});

