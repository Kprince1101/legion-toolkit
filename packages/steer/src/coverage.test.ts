withOxlint('Bash writes, checked after the command runs', () => {
  let dir = '';

  beforeEach(() => {
    dir = recommendedProject({
      'src/answer.ts': CLEAN,
      'src/legacy.ts': `${ENUM}${CLEAN}`,
      'gen.cjs': NODE_GEN,
      'gen.py': PYTHON_GEN,
      '.gitignore': 'ignored/\n',
    });
    commitAll(dir);
  });

  it.each([
    {
      path: 'echo redirection',
      command: "echo 'export enum Echoed { A }' > src/echoed.ts",
    },
    {
      path: 'cat heredoc',
      command:
        "cat <<'EOF' > src/heredoc.ts\nexport enum Heredoc {\n  A,\n}\nEOF",
    },
    {
      path: 'an append',
      command: "printf 'export enum Appended {\\n  A,\\n}\\n' >> src/answer.ts",
    },
    {
      path: 'sed -i',
      command:
        "sed -i.bak 's/const answer = 42;/enum Answer { A }/' src/answer.ts && rm src/answer.ts.bak",
    },
    { path: 'a node script', command: 'node gen.cjs' },
    { path: 'a python script', command: 'python3 gen.py' },
  ])('reports a violation written by $path', ({ command }) => {
    const verdict = throughBash(dir, command);
    expect(verdict.action).toBe('report');
    expect(rulesOf(verdict)).toContain('legion/no-enum');
  });

  it('reports a file-wide bypass a command writes', () => {
    const verdict = throughBash(
      dir,
      "printf '/* eslint-disable */\\nexport enum Hidden { A }\\n' > src/hidden.ts",
    );
    expect(verdict.action).toBe('report');
    expect(rulesOf(verdict)).toContain(FILE_WIDE_RULE);
  });

  it('only reports what the command added to a file that already had violations', () => {
    const verdict = throughBash(
      dir,
      "sed -i.bak 's/= 42/= 43/' src/legacy.ts && rm src/legacy.ts.bak",
    );
    expect(verdict.action).toBe('allow');
    expect(verdict.notices.join('\n')).toContain('already in this file');
  });

  it('leaves alone a dirty file the command did not touch', () => {
    const stale = put(dir, 'src/stale.ts', ENUM);
    const past = new Date(Date.now() - 60_000);
    utimesSync(stale, past, past);
    expect(throughBash(dir, 'echo notes > notes.md')).toMatchObject({
      action: 'allow',
      notices: [],
    });
  });

  it('does not see a file written where git ignores it', () => {
    expect(
      throughBash(
        dir,
        "mkdir -p ignored && echo 'export enum Hidden { A }' > ignored/hidden.ts",
      ),
    ).toMatchObject({ action: 'allow', notices: [] });
  });
});

